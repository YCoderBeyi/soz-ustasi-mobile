// Builds src/data/bonusWords.generated.ts from the reviewed vault list.
// Source of truth: vault/07-Production/bonus-lexicon-v1 (MPL 2.0 derived, see README there).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'vault', '07-Production', 'bonus-lexicon-v1');
const byLevel = JSON.parse(readFileSync(join(dir, 'allowlist-by-level.json'), 'utf8'));
const denied = new Set(Object.values(JSON.parse(readFileSync(join(dir, 'denied-by-values.json'), 'utf8'))).flat());

const normalize = (word) => word.trim().toLocaleUpperCase('tr-TR').normalize('NFC');
const words = [...new Set(Object.values(byLevel).flat().map(normalize))]
  .filter((word) => !denied.has(word) && [...word].length >= 3)
  .sort((a, b) => a.localeCompare(b, 'tr'));

// Original, short meanings written for this project (not copied from TDK). Missing entries stay meaning-less.
const authored = JSON.parse(readFileSync(join(dir, 'meanings.json'), 'utf8'));
const meanings = Object.fromEntries(
  words.filter((word) => authored[word]).map((word) => [word, authored[word]]),
);
const orphans = Object.keys(authored).filter((word) => !words.includes(word));
if (orphans.length) throw new Error(`meanings.json has words outside the allowlist: ${orphans.join(', ')}`);

const body = `// GENERATED by scripts/generate-bonus-lexicon.mjs - do not edit by hand.
// Source: vault/07-Production/bonus-lexicon-v1 (candidates derived from tdd-ai/hunspell-tr, MPL 2.0).
export const GENERATED_BONUS_WORDS: readonly string[] = ${JSON.stringify(words)};
export const GENERATED_BONUS_MEANINGS: Readonly<Record<string, string>> = ${JSON.stringify(meanings)};
`;
writeFileSync(join(root, 'src', 'data', 'bonusWords.generated.ts'), body);
console.log(`bonusWords.generated.ts: ${words.length} words`);
